export const ALL_ORCHESTRA_PRESETS: OrchestraPreset[] = [
  ...ARCO_PRESETS,
  ...CORNU_PRESETS,
  ...AULOS_PRESETS,
];

export function presetsForOrchestra(family: OrchestraFamily): OrchestraPreset[] {
  if (family === 'arco') return ARCO_PRESETS;
  if (family === 'cornu') return CORNU_PRESETS;
  return AULOS_PRESETS;
}

export function defaultOrchestraPreset(family: OrchestraFamily): OrchestraPreset {
  return presetsForOrchestra(family)[0];
}

export function orchestraPresetById(id?: string): OrchestraPreset | undefined {
  if (!id) return undefined;
  return ALL_ORCHESTRA_PRESETS.find((p) => p.id === id);
}
