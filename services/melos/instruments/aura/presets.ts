export type AuraMacro = 'warmth' | 'cutoff' | 'resonance' | 'aura' | 'ensemble' | 'space';

export interface AuraPreset {
  id: string;
  name: string;
  category: AuraCategory;
  year: string;
  inspiration: string;
  description: string;
  params: Record<number, number>;
  tables?: string[];
  macros: Record<AuraMacro, number>;
  routes?: AuraModRoute[];
  padX?: PadTarget[];
  padY?: PadTarget[];
  arp?: Partial<AuraArpConfig>;
}

const st = (semitones: number) => Math.max(0, Math.min(1, 0.5 + semitones / 48));
const ct = (cents: number) => Math.max(0, Math.min(1, 0.5 + cents / 200));

/**
 * Expand AURA's 6 front-panel macros into the underlying DSP parameters.
 * Neutral macro values leave preset parameters untouched; turning a macro up or down
 * scales the relevant vintage circuit stages together.
 */
export function expandAuraMacros(
  base: Record<number, number>,
  m: Record<AuraMacro, number>,
): Record<number, number> {
  const p = { ...base };
  const clamp = (v: number, lo = 0, hi = 1) => Math.max(lo, Math.min(hi, v));

  // 1. Warmth: Preamp discrete transistor warmth + Ladder filter drive + 15 IPS Tape saturation
  const wDelta = (m.warmth - 0.35) * 0.85;
  p[A.WARMTH] = clamp((p[A.WARMTH] ?? 0.3) + wDelta);
  p[flt(0, F.DRIVE)] = clamp((p[flt(0, F.DRIVE)] ?? 0.15) + wDelta * 0.65);
  p[A.TAPE_SAT] = clamp((p[A.TAPE_SAT] ?? 0.2) + wDelta * 0.55);

  // 2. Cutoff: Shifts primary and secondary filter cutoffs around the preset's voiced point
  const cDelta = (m.cutoff - 0.5) * 0.65;
  p[flt(0, F.CUTOFF)] = clamp((p[flt(0, F.CUTOFF)] ?? 0.65) + cDelta, 0.03, 0.99);
  if ((p[flt(1, F.ENABLE)] ?? 0) > 0.5) {
    p[flt(1, F.CUTOFF)] = clamp((p[flt(1, F.CUTOFF)] ?? 0.3) + cDelta * 0.5, 0.03, 0.99);
  }

  // 3. Resonance: Filter emphasis + slight envelope contour boost
  const rDelta = (m.resonance - 0.3) * 0.75;
  p[flt(0, F.RES)] = clamp((p[flt(0, F.RES)] ?? 0.18) + rDelta, 0, 0.96);

  // 4. Vintage Aura: Voice-card component tolerance, VCO drift, tape wow, and subtle studio hum/dust
  const aDelta = (m.aura - 0.35) * 0.85;
  p[A.AURA] = clamp((p[A.AURA] ?? 0.25) + aDelta);
  p[P.ANALOG_DRIFT] = clamp((p[P.ANALOG_DRIFT] ?? 0.28) + aDelta * 0.7);
  p[SP.EC_WOW] = clamp((p[SP.EC_WOW] ?? 0.3) + aDelta * 0.5);
  if (m.aura > 0.55) {
    const extraAge = (m.aura - 0.55) / 0.45;
    p[A.HUM] = clamp((p[A.HUM] ?? 0.04) + extraAge * 0.22);
    p[A.CRACKLE] = clamp((p[A.CRACKLE] ?? 0.0) + extraAge * 0.18);
  }

  // 5. Ensemble / Phase: BBD String Ensemble + 6-Stage Krautrock Phaser
  const eVal = m.ensemble;
  const phExplicit = (base[A.PH_ON] ?? 0) > 0.5;
  const ensExplicit = (base[A.ENS_ON] ?? 0) > 0.5;
  if (eVal > 0.04) {
    if (phExplicit && !ensExplicit) {
      p[A.PH_ON] = 1;
      p[A.PH_MIX] = clamp(Math.max(base[A.PH_MIX] ?? 0.4, (base[A.PH_MIX] ?? 0.45) * (0.4 + eVal * 1.1)));
      p[A.PH_DEPTH] = clamp((base[A.PH_DEPTH] ?? 0.7) * (0.6 + eVal * 0.6));
    } else {
      p[A.ENS_ON] = 1;
      p[A.ENS_MIX] = clamp(Math.max(base[A.ENS_MIX] ?? 0, eVal * 0.85));
      p[A.ENS_DEPTH] = clamp((base[A.ENS_DEPTH] ?? 0.6) * (0.55 + eVal * 0.65));
      if (phExplicit) {
        p[A.PH_ON] = 1;
        p[A.PH_MIX] = clamp(Math.max(base[A.PH_MIX] ?? 0.38, (base[A.PH_MIX] ?? 0.4) * (0.4 + eVal * 0.9)));
      }
    }
  } else {
    if (!ensExplicit) p[A.ENS_MIX] = 0;
    else p[A.ENS_MIX] = clamp(base[A.ENS_MIX] ?? 0.45);
    if (!phExplicit) p[A.PH_MIX] = 0;
    else p[A.PH_MIX] = clamp(base[A.PH_MIX] ?? 0.42);
  }

  // 6. Tape Space: Magnetic Tape Echo + Stereo Delay + Chamber/Spring Reverb
  const sVal = m.space;
  const ecExplicit = (base[SP.EC_ON] ?? 0) > 0.5;
  const dlExplicit = (base[SP.DL_ON] ?? 0) > 0.5;
  if (sVal > 0.03) {
    const baseRv = base[RV.MIX] ?? 0.15;
    p[RV.MIX] = clamp(Math.max(baseRv * (sVal / 0.35), sVal * 0.65), 0, 0.85);
    p[RV.DECAY] = clamp((base[RV.DECAY] ?? 0.45) + (sVal - 0.3) * 0.4, 0.15, 0.92);
    if (ecExplicit || sVal > 0.42) {
      p[SP.EC_ON] = 1;
      p[SP.EC_MIX] = clamp(Math.max(base[SP.EC_MIX] ?? 0.18, (sVal - 0.2) * 0.55), 0, 0.75);
    }
    if (dlExplicit) {
      p[SP.DL_ON] = 1;
      p[SP.DL_MIX] = clamp(Math.max(base[SP.DL_MIX] ?? 0.25, sVal * 0.55), 0, 0.75);
    }
  } else {
    p[RV.MIX] = 0;
    if (!ecExplicit) p[SP.EC_MIX] = 0;
    else p[SP.EC_MIX] = clamp(base[SP.EC_MIX] ?? 0.25);
    if (!dlExplicit) p[SP.DL_MIX] = 0;
    else p[SP.DL_MIX] = clamp(base[SP.DL_MIX] ?? 0.28);
  }

  return p;
}

