/**
 * lightShowEngine.ts — The core show document model for LD (Lighting Designer).
 *
 * A show is a tree: Show → CueList → Cue → FixtureState.
 * The engine interpolates between cues over time, supports snapping to beat
 * markers, and outputs a unified fixture bus that feeds all output adapters
 * (smart lights, DMX, screen sync, Pixels visualizer).
 *
 * Design philosophy: "Magic not math." DMX addresses auto-assign, fixture
 * profiles auto-detect, channel groups auto-label. The LD can always dig
 * deeper, but the default is delight.
 */

// ── Types ───────────────────────────────────────────────────────────────────

/** A color in HSL space — the natural space for lighting design (hue wheel, saturation, luminance). */
export interface LDColor {
  h: number; // 0-360
  s: number; // 0-100
  l: number; // 0-100
}

/** Fixture categories the engine knows about. */
export type FixtureKind =
  | 'SMART_BULB'     // Hue, Nanoleaf, Govee, generic Wi-Fi
  | 'SMART_STRIP'    // LED strips (Hue, Govee, WLED)
  | 'SCREEN'         // Any logged-in Plajah device (screen-as-fixture)
  | 'DMX_DIMMER'     // Single-channel dimmer
  | 'DMX_RGB'        // 3/4 channel RGB/RGBW par
  | 'DMX_MOVING'     // Moving head / scanner (pan/tilt/color/gobo)
  | 'DMX_LED_BAR'    // Multi-cell LED bar
  | 'DMX_STROBE'     // Strobe/blinder
  | 'DMX_LASER'      // Laser fixture
  | 'DMX_FOG'        // Fog/haze machine
  | 'RAZER_CHROMA'   // Razer Chroma peripherals
  | 'CUSTOM';        // User-defined

/** How a fixture transitions between states. */
export type TransitionType =
  | 'SNAP'      // Instant change (blackout, strobe)
  | 'FADE'      // Linear crossfade
  | 'EASE_IN'   // Smooth acceleration
  | 'EASE_OUT'  // Smooth deceleration
  | 'EASE'      // Smooth both directions
  | 'CHASE'     // Sequential through fixtures in the group
  | 'RAINBOW'   // Hue rotation through group
  | 'PULSE'     // Beat-synced pulse
  | 'BREATHE';  // Slow organic pulse

/** The state of a single fixture at a point in time. */
export interface FixtureState {
  /** Fixture or fixture-group ID this state applies to. */
  fixtureId: string;
  color: LDColor;
  /** 0-1, overall brightness. */
  intensity: number;
  /** For moving heads: 0-540 degrees. */
  pan?: number;
  /** For moving heads: 0-270 degrees. */
  tilt?: number;
  /** Strobe rate: 0 = off, 1 = slow, 10 = full. */
  strobe?: number;
  /** Gobo wheel position (DMX moving heads). */
  gobo?: number;
  /** Effect applied to this fixture. */
  effect?: TransitionType;
  /** Effect speed multiplier (1 = 1x tempo). */
  effectSpeed?: number;
}

/** A cue is a time-stamped lighting state for one or more fixtures. */
export interface Cue {
  id: string;
  /** Seconds from the start of the track (or show). */
  time: number;
  /** Duration of the transition into this cue, in seconds. */
  fadeDuration: number;
  /** How to transition into this cue. */
  transition: TransitionType;
  /** Fixture states at this cue point. */
  states: FixtureState[];
  /** Optional: which song section this cue is for (verse, chorus, bridge, etc.). */
  section?: string;
  /** Optional: label for the cue timeline ("Chorus burst", "Fade to blue", etc.). */
  label?: string;
  /** Whether this cue was auto-generated by the AI. */
  aiGenerated?: boolean;
  /** AI annotation / "Teach Me" explanation. */
  aiAnnotation?: string;
}

/** A scene is a saved preset — a named collection of fixture states. */
export interface Scene {
  id: string;
  name: string;
  /** Colors extracted from album art, or manually chosen. */
  palette: LDColor[];
  states: FixtureState[];
  /** Optional: the mood/energy this scene targets. */
  mood?: 'intimate' | 'energetic' | 'dramatic' | 'calm' | 'celebratory';
  thumbnail?: string;
}

/** A fixture in the user's rig (physical or virtual). */
export interface Fixture {
  id: string;
  kind: FixtureKind;
  name: string;
  /** Adapter-specific device ID (Hue light ID, DMX address, screen device ID, etc.). */
  adapterId: string;
  /** Which adapter manages this fixture. */
  adapter: 'HUE' | 'NANOLEAF' | 'GOVEE' | 'RAZER' | 'DMX_SERIAL' | 'ARTNET' | 'SACN' | 'SCREEN' | 'WLED';
  /** Position in the spatial fixture map. */
  position: { x: number; y: number };
  /** DMX start address (for DMX fixtures). */
  dmxAddress?: number;
  /** DMX channel count (for DMX fixtures). */
  dmxChannels?: number;
  /** Fixture profile ID from the Open Fixture Library. */
  profileId?: string;
  /** Group ID for fixture grouping (e.g., "front wash", "stage left"). */
  groupId?: string;
  /** Whether this fixture is online / reachable. */
  online: boolean;
  /** Capabilities this fixture supports. */
  capabilities: Array<'COLOR' | 'DIMMER' | 'PAN' | 'TILT' | 'STROBE' | 'GOBO' | 'FOG'>;
}

/** A fixture group — logical grouping for batch control. */
export interface FixtureGroup {
  id: string;
  name: string;
  fixtureIds: string[];
  /** Auto-assigned color for visual identification in the fixture map. */
  color: string;
}

/** A complete show document. */
export interface LightShow {
  id: string;
  name: string;
  /** The track or album this show is designed for. */
  trackId?: string;
  albumId?: string;
  /** All fixtures in the rig. */
  fixtures: Fixture[];
  /** Fixture groups. */
  groups: FixtureGroup[];
  /** Saved scene presets. */
  scenes: Scene[];
  /** The cue list — the "program" of the show. */
  cues: Cue[];
  /** BPM of the associated track (from audio analysis). */
  bpm?: number;
  /** Master intensity (0-1). */
  masterIntensity: number;
  /** Master speed multiplier. */
  masterSpeed: number;
  /** Whether the show is in Party Mode (auto-reactive, no cue list). */
  partyMode: boolean;
  createdAt: number;
  updatedAt: number;
}

