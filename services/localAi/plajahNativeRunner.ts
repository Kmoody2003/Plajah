// plajahNativeRunner.ts — Native execution dispatcher for Plajah Generative Studio.
// Executes generative diffusion tasks natively on-device:
//   1. Windows WinUI 3 Native Shell via DirectML & NVIDIA TensorRT (PlajahAiNativeService)
//
// If neither backend produces output the task FAILS (`success: false`). There is no
// procedural/canvas stand-in: a placeholder must never be reported as model output.
//
// Zero third-party vendor software (No ComfyUI, No external web servers).

import { PlajahNativeTask } from './plajahPipelineEngine';
import { isWindowsApp, getNativeMediaEngine } from '../windowsBridgeService';
import { encodeJxlViaSidecar } from '../jxlCodec';

export interface NativeExecutionProgress {
  taskId: string;
  step: number;
  totalSteps: number;
  percent: number;
  status: 'preparing' | 'loading_model' | 'denoising' | 'decoding_vae' | 'completed' | 'error';
  previewImageUrl?: string;
}

export interface NativeExecutionResult {
  success: boolean;
  taskId: string;
  mediaUrl: string; // Base64 or native plajah virtual URI (http://plajah.native/...)
  /** Native ISO/IEC 18181 JPEG XL (`data:image/jxl;base64,...`) master asset generated by the model. */
  jxlUrl?: string;
  /** 320px JPEG XL (`data:image/jxl;base64,...`) thumbnail generated alongside the model output. */
  thumbUrl?: string;
  /** Encoded image format ('jxl' by default). */
  format?: 'jxl' | 'webp' | 'png';
  byteSize?: number;
  thumbByteSize?: number;
  mediaType: 'image' | 'video' | 'vector';
  width: number;
  height: number;
  seed: number;
  executionTimeMs: number;
  /** `'FALLBACK'` only ever accompanies `success: false` — no backend ran. */
  hardwareBackend: 'WINDOWS_DIRECTML' | 'NVIDIA_TENSORRT' | 'BROWSER_WEBGPU' | 'FALLBACK';
  /** User-actionable failure message (set whenever `success` is false). */
  error?: string;
  /** `engine_offline`: nothing answered. `engine_error`: an engine answered but produced no output. */
  errorCode?: 'engine_offline' | 'engine_error';
}

/**
 * Post-generation JPEG XL copy creator: converts a generated PNG/WebP image URL
 * into a native ISO/IEC 18181 JPEG XL (`data:image/jxl;base64,...`) copy and a
 * 320px JPEG XL thumbnail after model generation has completed.
 */
export async function createJxlCopyAfterGeneration(
  sourceUrl: string,
  quality = 0.88
): Promise<{ jxlUrl: string; thumbUrl?: string; byteSize: number; thumbByteSize: number } | null> {
  if (!sourceUrl || sourceUrl.startsWith('data:image/jxl')) {
    return sourceUrl
      ? { jxlUrl: sourceUrl, thumbUrl: sourceUrl, byteSize: sourceUrl.length, thumbByteSize: sourceUrl.length }
      : null;
  }
  try {
    const res = await encodeJxlViaSidecar(sourceUrl, { quality, thumbEdge: 320 });
    if (res && res.dataUrl) {
      return {
        jxlUrl: res.dataUrl,
        thumbUrl: res.thumbDataUrl || res.dataUrl,
        byteSize: res.byteSize,
        thumbByteSize: res.thumbByteSize,
      };
    }
  } catch {
    // Non-fatal: primary PNG generation is already complete
  }
  return null;
}

/**
 * Execute a generative task directly through Plajah's native on-device runtime.
 */
export async function executePlajahNativeTask(
  task: PlajahNativeTask,
  onProgress?: (p: NativeExecutionProgress) => void
): Promise<NativeExecutionResult> {
  const startTime = Date.now();
  const totalSteps = Math.max(1, task.steps || 1);

  onProgress?.({
    taskId: task.id,
    step: 0,
    totalSteps,
    percent: 10,
    status: 'preparing',
  });

  // ── PRIORITY 1: Plajah Native GPU Sidecar on port 51122 or local server proxy ──
  const sidecarEndpoints = ['http://127.0.0.1:51122/generate'];
  if (typeof window !== 'undefined' && window.location?.origin && !window.location.origin.includes('51122')) {
    sidecarEndpoints.push(`${window.location.origin}/api/local-ai/generate`);
  }

  // Why no backend produced output — reported to the caller if every path fails.
  let engineReached = false;
  let engineError = '';

  for (const ep of sidecarEndpoints) {
    const ctrl = new AbortController();
    const timeoutId = setTimeout(() => ctrl.abort(), 90000);
    let curPct = 30;
    const progressTimer = setInterval(() => {
      curPct = Math.min(92, curPct + 6);
      onProgress?.({
        taskId: task.id,
        step: Math.min(totalSteps, Math.ceil((curPct / 100) * totalSteps)),
        totalSteps,
        percent: curPct,
        status: 'denoising',
      });
    }, 700);

    try {
      onProgress?.({
        taskId: task.id,
        step: 1,
        totalSteps,
        percent: 25,
        status: 'loading_model',
      });

      const resp = await fetch(ep, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          task,
          outputFormat: 'png_with_jxl_copy',
          clientSupportsJxlDecode: false,
        }),
        signal: ctrl.signal,
      });

      const data = await resp.json().catch(() => null);
      if (resp.ok && data && data.success && data.mediaUrl) {
        onProgress?.({
          taskId: task.id,
          step: totalSteps,
          totalSteps,
          percent: 100,
          status: 'completed',
          previewImageUrl: data.mediaUrl,
        });

        return {
          success: true,
          taskId: task.id,
          mediaUrl: data.mediaUrl,
          jxlUrl: data.jxlUrl,
          thumbUrl: data.thumbUrl,
          format: data.format || 'png',
          byteSize: data.byteSize,
          thumbByteSize: data.thumbByteSize,
          mediaType: task.taskType === 'cinema_motion' ? 'video' : 'image',
          width: data.width || task.dimensions.width,
          height: data.height || task.dimensions.height,
          seed: data.seed || task.seed,
          executionTimeMs: Date.now() - startTime,
          hardwareBackend: 'NVIDIA_TENSORRT',
        };
      }
      const detail = data?.error || data?.message || data?.detail;
      if (data && typeof data === 'object' && (resp.ok || detail)) {
        // The engine itself answered (JSON) but produced nothing; do not duplicate-queue on the proxy endpoint
        engineReached = true;
        engineError = String(detail || 'the engine returned no image');
        break;
      }
      // Non-JSON / bare HTTP error (e.g. a host with no local-AI proxy route): treat as "no engine here".
    } catch (e: any) {
      if (e?.name === 'AbortError') {
        engineReached = true;
        engineError = 'the engine did not finish within 90 seconds';
        break;
      }
      // Connection refused or network error on 127.0.0.1:51122 -> try proxy endpoint to auto-spawn sidecar
    } finally {
      clearInterval(progressTimer);
      clearTimeout(timeoutId);
    }
  }

  // ── PRIORITY 2: Windows Native App (WinUI 3 Shell with DirectML / TensorRT) ──
  if (isWindowsApp() && typeof window !== 'undefined') {
    const mediaEngine = getNativeMediaEngine();
    const invokeFn = typeof mediaEngine?.invokeNative === 'function'
      ? mediaEngine.invokeNative.bind(mediaEngine)
      : typeof mediaEngine?.invoke === 'function'
      ? mediaEngine.invoke.bind(mediaEngine)
      : null;

    if (invokeFn) {
      try {
        onProgress?.({
          taskId: task.id,
          step: 1,
          totalSteps,
          percent: 30,
          status: 'loading_model',
        });

        const nativeResponse = await invokeFn('ai_diffuse', {
          task,
          outputFormat: 'png_with_jxl_copy',
        });
        if (nativeResponse && nativeResponse.success && (nativeResponse.mediaUrl || nativeResponse.outputPath)) {
          onProgress?.({
            taskId: task.id,
            step: totalSteps,
            totalSteps,
            percent: 100,
            status: 'completed',
          });

          return {
            success: true,
            taskId: task.id,
            mediaUrl: nativeResponse.mediaUrl || nativeResponse.outputPath,
            jxlUrl: nativeResponse.jxlUrl,
            thumbUrl: nativeResponse.thumbUrl,
            format: nativeResponse.format || 'png',
            mediaType: task.taskType === 'cinema_motion' ? 'video' : 'image',
            width: task.dimensions.width,
            height: task.dimensions.height,
            seed: task.seed,
            executionTimeMs: Date.now() - startTime,
            hardwareBackend: 'NVIDIA_TENSORRT',
          };
        }
        engineReached = true;
        engineError = String(nativeResponse?.error || engineError || 'the Windows native engine returned no output');
      } catch (err: any) {
        console.warn('[PlajahNativeRunner] Windows native engine bridge error:', err);
        engineReached = true;
        engineError = String(err?.message || err);
      }
    }
  }

  // ── No backend produced output: fail honestly, never return a placeholder ──
  const error = engineReached
    ? `The local GPU engine could not complete this task: ${engineError || 'unknown error'}. ` +
      `Check that the model (${task.modelId}) is installed in the Plajah local engine, then try again.`
    : 'The Plajah local GPU engine is not running (no response from http://127.0.0.1:51122). ' +
      'Start the local engine and try again — nothing was generated.';

  onProgress?.({
    taskId: task.id,
    step: 0,
    totalSteps,
    percent: 0,
    status: 'error',
  });

  return {
    success: false,
    taskId: task.id,
    mediaUrl: '',
    mediaType: task.taskType === 'cinema_motion' ? 'video' : 'image',
    width: task.dimensions.width,
    height: task.dimensions.height,
    seed: task.seed,
    executionTimeMs: Date.now() - startTime,
    hardwareBackend: 'FALLBACK',
    error,
    errorCode: engineReached ? 'engine_error' : 'engine_offline',
  };
}
