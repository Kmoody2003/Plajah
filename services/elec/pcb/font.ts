/** Polylines for a string with its top-left at (x, y), cap height h (mm). */
export function textStrokes(s: string, x: number, y: number, h: number): Array<Array<[number, number]>> {
  const k = h / 6; const out: Array<Array<[number, number]>> = []; let cx = x;
  for (const ch of s.toUpperCase()) {
    for (const pl of G[ch] ?? []) { const pts: Array<[number, number]> = []; for (let i = 0; i < pl.length; i += 2) pts.push([cx + pl[i] * k, y + pl[i + 1] * k]); out.push(pts); }
    cx += 5.6 * k;
  }
  return out;
}
export const textWidth = (s: string, h: number) => Math.max(0, s.length * 5.6 - 1.6) * (h / 6);
