// services/livewire/origin.ts — the Livewire origin box: MediaMTX config + the master playlist route.
//
// MediaMTX (MIT) takes rungs in over SRT / RTMP / WHIP and packages each path as Low-Latency HLS.
// It never re-encodes desktop rungs, so one box carries hundreds of streams. Layout:
//   live/<streamId>/<rung>/index.m3u8   ← MediaMTX, one path per rung
//   live/<streamId>/master.m3u8         ← ours (originSidecar / API), built by manifest.ts
// The CDN pulls both from the origin and caches every segment once per region.
//
// Written for MediaMTX 1.9+. Key names have changed between releases (e.g. hlsAllowOrigin →
// hlsAllowOrigins); check this output against the installed version's mediamtx.yml.

import { buildMasterPlaylist } from './manifest';
import { GOP_SECONDS } from './encodeArgs';
import type { Rung } from './types';

export interface OriginConfigInput {
  /** Our auth endpoint MediaMTX calls before every publish/read. */
  authUrl: string;
  /** Allowed browser origins for direct (non-CDN) dev playback. */
  allowOrigins?: string[];
  segmentSeconds?: number;
  partMs?: number;
  /** Turn on WHIP/WHEP (browser publish + sub-second preview). */
  webrtc?: boolean;
}

const RUNG_PATH_RE = '~^live/[A-Za-z0-9_-]{6,128}/(1080p|720p|480p|360p|av1_1080p|av1_720p|audio)$';

export function mediamtxConfig(c: OriginConfigInput): string {
  const seg = c.segmentSeconds ?? GOP_SECONDS;
  const part = c.partMs ?? 200;
  const origins = (c.allowOrigins?.length ? c.allowOrigins : ['*']).map(o => `'${o}'`).join(', ');
  return [
    '# Livewire origin — generated by services/livewire/origin.ts. Do not hand-edit; regenerate.',
    'logLevel: info',
    '',
    '# Every publish/read is decided by Plajah (services/livewire/token.ts decideOriginAuth).',
    'authMethod: http',
    `authHTTPAddress: ${c.authUrl}`,
    '',
    'api: yes',
    'apiAddress: 127.0.0.1:9997',
    'metrics: yes',
    'metricsAddress: 127.0.0.1:9998',
    '',
    'rtsp: no',
    'rtmp: yes',
    'rtmpAddress: :1935',
    'srt: yes',
    'srtAddress: :8890',
    `webrtc: ${c.webrtc ? 'yes' : 'no'}`,
    'webrtcAddress: :8889',
    '',
    '# Low-Latency HLS: segments cut on the forced keyframes, parts for ~2-4 s glass-to-glass.',
    'hls: yes',
    'hlsAddress: :8888',
    'hlsVariant: lowLatency',
    `hlsSegmentDuration: ${seg}s`,
    `hlsPartDuration: ${part}ms`,
    'hlsSegmentCount: 7',
    `hlsAllowOrigins: [${origins}]`,
    '',
    'paths:',
    `  '${RUNG_PATH_RE}':`,
    '    source: publisher',
    '    # A reconnecting broadcaster replaces its own stale session instead of being refused.',
    '    overridePublisher: yes',
    '',
  ].join('\n');
}

/** The master playlist the origin serves at live/<streamId>/master.m3u8. */
export function originMaster(rungs: Rung[]): string {
  return buildMasterPlaylist(rungs, { uriFor: r => `${r.name}/index.m3u8` });
}
