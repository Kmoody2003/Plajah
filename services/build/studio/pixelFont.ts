export const FONT_ROWS = 7, FONT_COLS = 5;
/** Characters the lettering supports (lower case is shown in capitals). */
export const FONT_CHARS = Object.keys(G).join('');

/** The text as a grid of filled cells: rows top to bottom, one column gap between letters. */
export function textGrid(text: string): boolean[][] {
  const chars = [...(text || ' ').toUpperCase()].map(c => (c === '♥' ? '<' : c)).filter(c => G[c] !== undefined);
  if (!chars.length) chars.push(' ');
  const cols = chars.length * (FONT_COLS + 1) - 1;
  const grid = Array.from({ length: FONT_ROWS }, () => new Array<boolean>(cols).fill(false));
  chars.forEach((c, i) => G[c].forEach((row, r) => { for (let k = 0; k < FONT_COLS; k++) if (row[k] === '#') grid[r][i * (FONT_COLS + 1) + k] = true; }));
  return grid;
}
