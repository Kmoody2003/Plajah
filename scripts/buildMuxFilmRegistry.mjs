/**
 * Builds data/muxFilmRegistry.ts from the local film vault's mux.json sidecars.
 *
 * Production (Cloud Run) has no film vault on disk, so without this committed
 * registry it never sees the Mux playback IDs and falls back to slow archive.org
 * MP4s (or re-ingests the film into a brand-new Mux asset on every cold start).
 * Only playback IDs whose public HLS manifest answers 200 are written.
 *
 *   node scripts/buildMuxFilmRegistry.mjs [vaultDir]
 */
import fs from 'node:fs';
import path from 'node:path';

const vaultDir = process.argv[2] || 'D:/plajah-media/films';
const outFile = path.resolve('data/muxFilmRegistry.ts');

const entries = [];
for (const id of fs.readdirSync(vaultDir).sort()) {
  const muxFile = path.join(vaultDir, id, 'mux.json');
  if (!fs.existsSync(muxFile)) continue;
  try {
    const meta = JSON.parse(fs.readFileSync(muxFile, 'utf8'));
    if (meta?.muxPlaybackId) entries.push({ id, playbackId: meta.muxPlaybackId, assetId: meta.muxAssetId || '' });
  } catch {}
}

const probe = async (playbackId) => {
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(`https://stream.mux.com/${playbackId}.m3u8`);
      return res.status;
    } catch {}
  }
  return 0;
};

const statuses = new Map();
const queue = [...entries];
await Promise.all(Array.from({ length: 16 }, async () => {
  while (queue.length) {
    const e = queue.shift();
    statuses.set(e.id, await probe(e.playbackId));
  }
}));

const ready = entries.filter((e) => statuses.get(e.id) === 200);
const broken = entries.filter((e) => statuses.get(e.id) !== 200);

const lines = ready.map((e) => `  ${JSON.stringify(e.id)}: { muxPlaybackId: ${JSON.stringify(e.playbackId)}, muxAssetId: ${JSON.stringify(e.assetId)} },`);
fs.writeFileSync(outFile, `// Generated by scripts/buildMuxFilmRegistry.mjs — do not edit by hand.
// Verified-ready public Mux playback IDs for the curated public-domain catalog,
// keyed by archive identifier. Rebuild after ingesting new films into Mux.
export const MUX_FILM_REGISTRY: Record<string, { muxPlaybackId: string; muxAssetId: string }> = {
${lines.join('\n')}
};
`);

console.log(`wrote ${ready.length} ready entries to ${path.relative(process.cwd(), outFile)}`);
for (const e of broken) console.log(`skipped ${e.id} (HLS ${statuses.get(e.id)})`);
