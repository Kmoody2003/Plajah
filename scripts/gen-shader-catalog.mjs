// Generates services/shaders/shaderCatalog.generated.ts from the installed `shaders` package's own registry.
// Re-run after bumping the pinned version:  node scripts/gen-shader-catalog.mjs
// The catalog is what the look validator and the Art Council prompt are grounded in, so a council look can
// only name components/props the library really has, with the library's own ranges.
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import path from 'node:path';

const reg = await import(pathToFileURL(path.resolve('node_modules/shaders/dist/registry.js')).href);
const pkg = JSON.parse((await import('node:fs')).readFileSync('node_modules/shaders/package.json', 'utf8'));

const kindOf = (ui) => {
  const t = Array.isArray(ui?.type) ? ui.type[0] : ui?.type;
  if (t === 'range' || t === 'number') return 'n';
  if (t === 'color') return 'c';
  if (t === 'select') return 's';
  if (t === 'toggle' || t === 'checkbox' || t === 'boolean') return 'b';
  if (t === 'text' || t === 'string') return 't';
  return 'x'; // image-upload, position, angle, stops… — not council-settable, defaults only
};

const out = {};
const kinds = {};
for (const s of reg.getAllShaders()) {
  const p = {};
  for (const [name, m] of Object.entries(s.propsMetadata ?? {})) {
    const ui = m.ui ?? {};
    const k = kindOf(ui);
    kinds[Array.isArray(ui.type) ? ui.type.join('|') : ui.type ?? 'none'] = (kinds[Array.isArray(ui.type) ? ui.type.join('|') : ui.type ?? 'none'] ?? 0) + 1;
    const e = { k };
    if (k === 'n') { if (typeof ui.min === 'number') e.min = ui.min; if (typeof ui.max === 'number') e.max = ui.max; }
    if (k === 's') e.o = (ui.options ?? []).map(o => o.value);
    if (m.default !== undefined && ['string', 'number', 'boolean'].includes(typeof m.default)) e.d = m.default;
    // `map` in ui.type means the prop can be driven by another layer's output — informational.
    p[name] = e;
  }
  out[s.name] = { c: s.category, d: (s.description ?? '').slice(0, 140), rc: !!s.requiresChild, p };
}

const body = `// GENERATED by scripts/gen-shader-catalog.mjs from shaders@${pkg.version} — do not hand-edit.
// k: n=number(min/max) c=color s=select(o=options) b=boolean t=text x=not council-settable.
export type CatalogProp = { k: 'n' | 'c' | 's' | 'b' | 't' | 'x'; min?: number; max?: number; o?: string[]; d?: string | number | boolean };
export type CatalogEntry = { c: string; d: string; rc: boolean; p: Record<string, CatalogProp> };
export const SHADER_CATALOG_VERSION = ${JSON.stringify(pkg.version)};
export const SHADER_CATALOG: Record<string, CatalogEntry> = ${JSON.stringify(out)};
`;
writeFileSync('services/shaders/shaderCatalog.generated.ts', body);
console.log('components', Object.keys(out).length, 'bytes', body.length, 'ui types', JSON.stringify(kinds));
