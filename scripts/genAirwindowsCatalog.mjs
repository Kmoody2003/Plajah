// Generates services/melos/beats/fx/airwindowsCatalog.generated.ts and public/airwindows/*.wasm
// from the compiled effects, keeping only those that matched their native C++ build.
//   node scripts/buildAirwindowsAll.mjs
//   node rust/plajah-airwindows/ref/build-all.mjs
//   node rust/plajah-airwindows/test/all-wasm.mjs
//   node scripts/genAirwindowsCatalog.mjs
// Knob names and defaults come from the compiled plug-in itself; one-line descriptions and
// categories from Airwindows' own what.txt and Airwindopedia.txt. The Rust-ported 16 keep their
// entries in fx/airwindows.ts and get no wasm here (saved projects depend on them).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..');
const wasmDir = process.argv[2] || path.join(root, 'rust/plajah-airwindows/ref/wasm');
const src = process.env.AIRWINDOWS_SRC || path.join(os.homedir(), 'oss/airwindows');
const report = JSON.parse(fs.readFileSync(path.join(root, 'rust/plajah-airwindows/ref/report.json'), 'utf8'));
const rust = new Set(fs.readFileSync(path.join(root, 'rust/plajah-airwindows/ref/plugins.txt'), 'utf8').split(/\r?\n/).filter((l) => l && !l.startsWith('#')));
const TOL = 1e-4;

const what = new Map();
for (const line of fs.readFileSync(path.join(src, 'what.txt'), 'utf8').split(/\r?\n/)) {
  const m = line.match(/^(\S+) (.*?)\s*\[coll=(.*)\]\s*$/);
  if (m) what.set(m[1], { blurb: `${m[1]} ${m[2]}`, rec: /Recommended/.test(m[3]) });
}
const groupOf = new Map();
const pedia = fs.readFileSync(path.join(src, 'Airwindopedia.txt'), 'utf8');
const cats = pedia.slice(pedia.indexOf('# Categories'), pedia.indexOf('############'));
for (const line of cats.split(/\r?\n/)) {
  const m = line.match(/^([A-Z][\w -]*): (.+)$/);
  if (m) for (const n of m[2].split(',')) groupOf.set(n.trim(), m[1]);
}

const cstr = (x, p) => { const b = new Uint8Array(x.memory.buffer); let e = p; while (b[e]) e++; return new TextDecoder('latin1').decode(b.subarray(p, e)).trim(); };
const pub = path.join(root, 'public/airwindows');
fs.rmSync(pub, { recursive: true, force: true });
fs.mkdirSync(pub, { recursive: true });

const entries = []; const skipped = []; const rustGroups = {};
for (const r of report) {
  if (rust.has(r.name)) { rustGroups[r.name] = groupOf.get(r.name) ?? 'Other'; continue; }
  if (!r.ok || !(r.worst <= TOL)) { skipped.push(`${r.name} (worst ${r.worst})`); continue; }
  const bytes = fs.readFileSync(path.join(wasmDir, `${r.name}.wasm`));
  const x = new WebAssembly.Instance(new WebAssembly.Module(bytes), {}).exports; x._initialize();
  const n = x.aw_init(0, 48000, 1, 1);
  const params = [];
  for (let i = 0; i < n; i++) {
    const def = x.aw_param_default(i);
    params.push([cstr(x, x.aw_param_name(i)) || `Param ${i + 1}`, +def.toFixed(6)]);
  }
  const w = what.get(r.name);
  entries.push({ name: r.name, group: groupOf.get(r.name) ?? 'Other', blurb: w?.blurb ?? '', rec: !!w?.rec, cpu: Math.round(r.xrt * 100), params });
  fs.writeFileSync(path.join(pub, `${r.name}.wasm`), bytes);
}
const body = `// GENERATED by scripts/genAirwindowsCatalog.mjs. Do not edit. Airwindows by Chris Johnson, MIT.
export interface AwCatalogEntry { name: string; group: string; blurb: string; rec: boolean; cpu: number; params: [string, number][] }
export const AW_RUST_GROUPS: Record<string, string> = ${JSON.stringify(rustGroups)};
export const AW_CATALOG: AwCatalogEntry[] = [
${entries.map((e) => JSON.stringify(e)).join(',\n')},
];
`;
fs.writeFileSync(path.join(root, 'services/melos/beats/fx/airwindowsCatalog.generated.ts'), body);
console.log(`catalog ${entries.length}, skipped ${skipped.length}, ${(body.length / 1024).toFixed(0)} KB`);
skipped.forEach((s) => console.log('SKIPPED', s));
console.log('groups', JSON.stringify(entries.reduce((a, e) => ({ ...a, [e.group]: (a[e.group] || 0) + 1 }), {})));
