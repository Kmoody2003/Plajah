import type { Question, QuestionBank } from './types';

const CID = 'econ-school';

/** Multiple choice builder: (lessonId, n, level, prompt, choices, answerIndex, hint, explanation). */
function mc(
  lessonId: string,
  n: number,
  level: 1 | 2 | 3,
  prompt: string,
  choices: string[],
  answer: number,
  hint: string,
  explanation: string,
): Question {
  return { id: `${CID}.${lessonId}.q${n}`, lessonId, kind: 'mcq', prompt, choices, answer, hint, explanation, level };
}

/** True/false builder: answer 0 = True, 1 = False. */
function tf(
  lessonId: string,
  n: number,
  level: 1 | 2 | 3,
  prompt: string,
  answer: 0 | 1,
  hint: string,
  explanation: string,
): Question {
  return { id: `${CID}.${lessonId}.q${n}`, lessonId, kind: 'tf', prompt, answer, hint, explanation, level };
}

