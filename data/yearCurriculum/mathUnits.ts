// Math scope & sequence, K–8: 36 weeks per grade, following the CCSS-M progression and each grade's critical areas.
//
//   Each grade opens with a short launch/review unit and closes with a cumulative review + project unit.
//   `ccss` is written short here ('3.OA.C.7') and expanded to the full 'CCSS.MATH.CONTENT.3.OA.C.7' form below.
//   `skills` key into services/yearCurriculum/mathSkills.ts; `params` pin the grade-appropriate range.
//   `intl`: England NC (Year = grade + 1), Cambridge (Stage = grade + 1), IB PYP phase / MYP year, Singapore MOE.

import type { SkillRef, UnitSpec, YearGrade } from '../../services/yearCurriculum/types';

type UnitDraft = Omit<UnitSpec, 'id' | 'grade' | 'subject' | 'n'>;

const s = (skill: string, can: string, params?: SkillRef['params']): SkillRef => (params ? { skill, params, can } : { skill, can });

const grade = (g: YearGrade, units: UnitDraft[]): UnitSpec[] =>
  units.map((u, i) => ({
    ...u,
    id: `math-${g}-u${String(i + 1).padStart(2, '0')}`,
    grade: g,
    subject: 'math',
    n: i + 1,
    ccss: u.ccss.map(c => `CCSS.MATH.CONTENT.${c}`),
  }));

