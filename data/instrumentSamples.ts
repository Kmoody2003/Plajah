// ─────────────────────────────────────────────────────────────────────────────
// instrumentSamples.ts — REAL recordings of real instruments, for the "Hear it"
// button in <InstrumentPrimers>.
//
// The synthesiser in services/instrumentSynth.ts gave every family one voice, and
// a trumpet ended up sounding like a cello. Synthesis cannot fake timbre, so this
// map points at actual solo recordings instead. instrumentSynth stays as the
// fallback for the instruments below that have no entry here, and for browsers
// that cannot decode the format we found (see services/instrumentAudio.ts).
//
// SOURCING RULES — every entry in this file was:
//   1. found through the Wikimedia Commons API or the Internet Archive metadata API
//      (never a hand-guessed URL),
//   2. checked against the file's OWN title and description to confirm it really is
//      the instrument it is filed under, and
//   3. HTTP range-requested and confirmed to answer 206 with an audio/* content type.
// Instruments we could not source honestly are simply absent — they fall back to
// the synthesiser rather than play something mislabelled.
//
// LICENSING: CC BY and CC BY-SA REQUIRE visible attribution. <HearIt> renders
// `attribution` + `license` whenever a sample (rather than the synth) is playing,
// so do not add an entry without filling those fields in.
//
// FORMAT: most Commons audio is uploaded as Ogg Vorbis, which Safari and iOS
// WebViews cannot decode — and this app ships inside a Capacitor WebView, so that
// would have stranded most instruments on the synth for iOS users. Commons however
// publishes an MP3 derivative of every audio file under /transcoded/, so `url`
// points at that MP3 (verified 206 audio/mpeg for all 78 non-MP3 originals) and
// `originalUrl` records the file we actually sourced and licence-checked. Same
// recording, same licence, universally playable. The player still walks the list
// and still falls back to the synth, because a format check can always be wrong.
// ─────────────────────────────────────────────────────────────────────────────

export interface InstrumentSample {
  /** Direct, verified media URL — the MP3 derivative where one exists. */
  url: string;
  /** Server-reported MIME type of `url` — used with HTMLAudioElement.canPlayType(). */
  mime: string;
  /** The originally uploaded file, when `url` is a transcode of it. Provenance only. */
  originalUrl?: string;
  /** MIME type of `originalUrl`. */
  originalMime?: string;
  /** What you actually hear, in one line. Shown under the player. */
  note: string;
  /** Human-readable licence, e.g. 'CC BY-SA 4.0' | 'CC0' | 'Public domain'. */
  license: string;
  /** Canonical licence deed, where the source documents one. */
  licenseUrl?: string;
  /** Performer or uploader — legally required for the CC BY / CC BY-SA entries. */
  attribution: string;
  /** The file's description page, so a user can check the licence themselves. */
  sourcePageUrl: string;
  /** Payload size in bytes, so the UI can warn before a large download. */
  bytes?: number;
}

