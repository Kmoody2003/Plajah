/** Verified recordings for an instrument, best-format-first. Never null. */
export const getInstrumentSamples = (instrumentId: string): InstrumentSample[] =>
  INSTRUMENT_SAMPLES[instrumentId] ?? [];

/** True when we have at least one real recording — i.e. the synth is not the only option. */
export const hasInstrumentSample = (instrumentId: string): boolean =>
  (INSTRUMENT_SAMPLES[instrumentId]?.length ?? 0) > 0;

/**
 * CC BY and CC BY-SA are the licences that legally oblige us to name the author.
 * CC0 and public-domain entries do not, but we credit them anyway — this only
 * exists so the UI can mark the required ones.
 */
export const attributionRequired = (sample: InstrumentSample): boolean =>
  /^CC BY/i.test(sample.license);

export default INSTRUMENT_SAMPLES;
