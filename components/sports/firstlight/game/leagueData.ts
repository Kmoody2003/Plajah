export function cloneTeam(id: string): SolLeagueTeam {
  const base = SOL_TEAMS[id] || SOL_TEAMS.AURORA;
  return {
    ...base,
    ratings: { ...base.ratings },
    starPlayers: { ...base.starPlayers },
    score: 0,
    timeouts: 3,
  };
}

export function resolveMatchupKits(home: TeamInfo, away: TeamInfo): { homeKit: TeamInfo; awayKit: TeamInfo } {
  const awayKit: TeamInfo = {
    ...away,
    primaryColor: away.awayPrimaryColor || '#f8fafc',
    secondaryColor: away.awaySecondaryColor || away.primaryColor,
    textColor: '#0f172a',
  };
  return { homeKit: home, awayKit };
}
